document.getElementById("borrowingForm").addEventListener(
    "submit",
    async function(event) {
        event.preventDefault();

        const studentId = document.getElementById(
            "borrowStudentId"
        ).value.trim();

        const bookId = document.getElementById(
            "borrowBookId"
        ).value.trim();

        const borrowingDate = document.getElementById("borrowDate").value;
        const dueDate = document.getElementById("dueDate").value;

        // Find the student using their registration number
        const student = students.find(function(item) {
            return item.id.toLowerCase() === studentId.toLowerCase();
        });

        if (!student) {
            alert("Student not found. Register the student first.");
            return;
        }

        // Find the book using its ISBN
        const book = books.find(function(item) {
            return item.id.toLowerCase() === bookId.toLowerCase();
        });

        if (!book) {
            alert("Book not found. Register the book first.");
            return;
        }

        // Validate the dates
        if (!borrowingDate || !dueDate || dueDate < borrowingDate) {
            alert(
                "Enter valid dates. The due date cannot be before the borrowing date."
            );
            return;
        }

        // Check the available copies
        if (book.copies <= 0) {
            alert("No copies of this book are currently available.");
            return;
        }

        // Prepare the borrowing information for the backend
        const borrowingData = {
            studentId: String(student.apiId),
            bookId: String(book.apiId),
            borrowDate: borrowingDate,
            dueDate: dueDate
        };

        try {
            // Save the borrowing in the backend and MySQL
            const response = await apiFetch(BORROWING_API_URL, {
                method: "POST",
                headers: {
                    "Content-Type": "application/json"
                },
                body: JSON.stringify(borrowingData)
            });

            if (!response.ok) {
                const errorMessage = await response.text();

                throw new Error(
                    errorMessage || "Failed to record the borrowing."
                );
            }

            // Update the frontend using the saved database record
            const savedBorrowing = await response.json();

            borrowings.push({
                id: savedBorrowing.id,
                studentId: student.id,
                studentName: student.name,
                bookId: book.id,
                bookTitle: book.title,
                borrowingDate: savedBorrowing.borrowDate,
                dueDate: savedBorrowing.dueDate,
                status: "Borrowed"
            });

            // Update the book quantity shown on the page
            book.copies--;

            displayBorrowings();
            displayBooks();
            updateBookDashboard();
            updateBorrowingDashboard();

            document.getElementById("borrowingForm").reset();

            alert("Book borrowed successfully!");

        } catch (error) {
            console.error("Borrowing error:", error);

            alert(
                "Could not borrow the book. " +
                "Please check that the backend is running and try again.\n\n" +
                error.message
            );
        }
    }
);

