// FINES
// ======================================================

function calculateOverdueDays(dueDate, returnDate) {
    const due = new Date(dueDate + "T00:00:00Z");
    const returned = new Date(returnDate + "T00:00:00Z");

    const difference = returned.getTime() - due.getTime();

    const days = Math.floor(
        difference / (1000 * 60 * 60 * 24)
    );

    return Math.max(0, days);
}

function calculateFine(dueDate, returnDate) {
    return calculateOverdueDays(dueDate, returnDate) * FINE_PER_DAY;
}


function displayFines() {
    const tableBody = document.getElementById("finesTableBody");

    if (!tableBody) {
        return;
    }

    tableBody.replaceChildren();

    let totalFines = 0;

    // Get today's date in YYYY-MM-DD format
    const today = getTodayDate();

    borrowings.forEach(function(record) {
        const isReturned = record.status === "Returned";

        // Use the actual return date for returned books.
        // For unreturned books, use today's date.
        const calculationDate = isReturned
            ? record.returnDate
            : today;

        if (!calculationDate) {
            return;
        }

        const overdueDays = calculateOverdueDays(
            record.dueDate,
            calculationDate
        );

        const fine = calculateFine(
            record.dueDate,
            calculationDate
        );

        // Don't display records with no overdue fine.
        if (fine <= 0) {
            return;
        }

        totalFines += fine;

        const row = document.createElement("tr");

        [
            record.id,
            `${record.studentName} (${record.studentId})`,
            `${record.bookTitle} (${record.bookId})`,
            record.dueDate,
            isReturned ? record.returnDate : "Not returned",
            overdueDays,
            "KES " + fine
        ].forEach(function(value) {
            const cell = document.createElement("td");

            cell.textContent = value;
            row.appendChild(cell);
        });

        tableBody.appendChild(row);
    });

    const totalFinesElement = document.getElementById("totalFines");

    if (totalFinesElement) {
        totalFinesElement.textContent = "KES " + totalFines;
    }
}
