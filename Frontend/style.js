async function returnBook(transactionId) {
    const record = borrowings.find(function(item) {
        return item.id === transactionId;
    });

    if (!record) {
        alert("Borrowing transaction not found.");
        return;
    }

    if (record.status !== "Borrowed") {
        alert("This book has already been returned.");
        return;
    }

    const confirmed = confirm(
        "Confirm that this book has been returned?"
    );

    if (!confirmed) {
        return;
    }

    try {
        const response = await apiFetch(`${BORROWING_API_URL}/${record.id}/return`, {
                method: "PUT"
            }
        );

        if (!response.ok) {
            const errorMessage = await response.text();

            throw new Error(
                errorMessage || "Failed to return the book."
            );
        }

        // Reload borrowing records and book quantities from the backend
        await loadBooks();
        await loadBorrowings();

        // Refresh the Returns and Fines sections
        displayReturns();
        displayFines();

        alert("Book returned successfully!");

    } catch (error) {
        console.error("Return error:", error);

        alert(
            "Could not return the book. Please try again.\n\n" +
            error.message
        );
    }
}

