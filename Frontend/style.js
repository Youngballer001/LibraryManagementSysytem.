document.getElementById("bookForm").addEventListener(
    "submit",
    async function(event) {
        event.preventDefault();

        const bookId = document.getElementById("bookId").value.trim();
        const title = document.getElementById("bookTitle").value.trim();
        const author = document.getElementById("bookAuthor").value.trim();
        const copies = Number(
            document.getElementById("bookCopies").value
        );

        if (
            !bookId ||
            !title ||
            !author ||
            !Number.isSafeInteger(copies) ||
            copies < 1
        ) {
            alert(
                "Enter a book ID, title, author, and a whole number " +
                "of copies greater than zero."
            );
            return;
        }

        const duplicate = books.some(function(book) {
            return book.id.toLowerCase() === bookId.toLowerCase();
        });

        if (duplicate) {
            alert("A book with this ID already exists.");
            return;
        }

        // Match the fields expected by the Java Book entity.
        const newBook = {
            title: title,
            author: author,
            isbn: bookId,
            quantity: copies
        };

        try {
            const response = await apiFetch(`${AUTH_API_URL}/logout`, {
    method: "POST",
    headers: {
        "Content-Type": "application/json"
    },
    body: JSON.stringify({})
});

            if (!response.ok) {
                const message = await response.text();

                throw new Error(
                    message || "The backend could not register the book."
                );
            }

            const savedBook = await response.json();

            books.push(convertBookFromAPI(savedBook));

            displayBooks();
            updateDashboard();

            document.getElementById("bookForm").reset();

            alert("Book added successfully and saved to MySQL!");

        } catch (error) {
            console.error("Error registering book:", error);

            alert(
                "The book could not be saved. Check that Spring Boot " +
                "is running and that the book ID has not already been used."
            );
        }
    }
);

