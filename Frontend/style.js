// The frontend uses the entered book ID as the ISBN field.
// apiId stores the numeric ID generated by MySQL.

let books = [];
let students = [];
let borrowings = [];
let nextBorrowingId = 1;

// Convert a backend book into the format used by the frontend.
function convertBookFromAPI(book) {
    return {
        id: String(book.isbn || book.id),
        apiId: book.id,
        title: book.title,
        author: book.author,
        copies: book.quantity
    };
}

// Load books from Spring Boot.
async function loadBooks() {
    try {
       const response = await apiFetch(API_URL);

        if (!response.ok) {
            throw new Error("Could not retrieve books.");
        }

        const data = await response.json();

        books = data.map(convertBookFromAPI);

        displayBooks();
        updateDashboard();

    } catch (error) {
        console.error("Error loading books:", error);

        alert(
            "Could not load books from the Java backend. " +
            "Make sure Spring Boot is running on port 8080."
        );
    }
}

