async function loadBorrowings() {
    try {
        const response = await apiFetch(BORROWING_API_URL)

        if (!response.ok) {
            throw new Error("Failed to load borrowing records.");
        }

        const savedBorrowings = await response.json();

        borrowings = savedBorrowings.map(function(record) {
            return {
                id: record.id,
                studentId: record.student.regNo,
                studentName: record.student.name,
                bookId: record.book.isbn,
                bookTitle: record.book.title,
                borrowingDate: record.borrowDate,
                dueDate: record.dueDate,
                returnDate: record.returnDate,
                status: record.status === "BORROWED"
                    ? "Borrowed"
                    : record.status === "RETURNED"
                        ? "Returned"
                        : record.status
            };
        });

        // Refresh the borrowing table and dashboard
        displayBorrowings();
        updateBorrowingDashboard();

        // Refresh returns and fines using the latest database records
        displayReturns();
        displayFines();

    } catch (error) {
        console.error("Error loading borrowing records:", error);

        alert(
            "Could not load borrowing records. " +
            "Check that your backend is running."
        );
    }
}



